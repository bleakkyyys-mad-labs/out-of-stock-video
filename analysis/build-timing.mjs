// kicks.json -> ../timing.js (window.OOS), loadable from file:// by a <script> tag.
// Snaps kicks to a least-squares 150 BPM half-beat grid, derives breaks / drops / vocal regions.
import fs from "fs";

const { kicks, env } = JSON.parse(fs.readFileSync("kicks.json", "utf8"));
const P = 0.4, HALF = P / 2;

// first pass: phase by circular mean, then least-squares fit t = a + b*n on on-grid kicks
let sx = 0, sy = 0;
kicks.forEach(k => { const a = 2 * Math.PI * (k.t % P) / P; sx += Math.cos(a); sy += Math.sin(a); });
const ph = ((Math.atan2(sy, sx) / (2 * Math.PI)) * P + P) % P;
const pts = kicks.map(k => ({ n: Math.round((k.t - ph) / HALF), t: k.t }))
  .filter(p => Math.abs(p.t - (ph + p.n * HALF)) < 0.06);
const N = pts.length, mn = pts.reduce((s, p) => s + p.n, 0) / N, mt = pts.reduce((s, p) => s + p.t, 0) / N;
const b = pts.reduce((s, p) => s + (p.n - mn) * (p.t - mt), 0) / pts.reduce((s, p) => s + (p.n - mn) ** 2, 0);
const a = mt - b * mn;
const bpm = 60 / (2 * b);

const snapped = kicks.map(k => {
  const n = Math.round((k.t - a) / b), g = a + n * b;
  const on = Math.abs(k.t - g) < 0.06;
  return { t: +(on ? g : k.t).toFixed(4), a: k.a, off: n % 2 !== 0 };   // off = lands on a half-beat
});

// vocal regions from the 20 fps envelopes
function regions(arr, th, minOn, minGap) {
  const raw = []; let s = -1;
  for (let i = 0; i <= arr.length; i++) {
    const on = i < arr.length && arr[i] > th;
    if (on && s < 0) s = i;
    if (!on && s >= 0) { raw.push([s / 20, i / 20]); s = -1; }
  }
  const m = [];
  raw.forEach(g => { if (m.length && g[0] - m.at(-1)[1] < minGap) m.at(-1)[1] = g[1]; else m.push(g); });
  return m.filter(g => g[1] - g[0] >= minOn).map(g => [+g[0].toFixed(2), +g[1].toFixed(2)]);
}
const backing = regions(env.backing, 30, 0.5, 1.2);
const lead = regions(env.lead, 25, 0.1, 0.25);

// breaks = kick-free stretches > 2 s; a drop = the kick coming back after a break with the shouted voice active
const breaks = [], drops = [];
for (let i = 1; i < snapped.length; i++) {
  const g0 = snapped[i - 1].t, g1 = snapped[i].t;
  if (g1 - g0 > 2) {
    breaks.push([g0, g1]);
    if (backing.some(([s, e]) => s < g1 + 1 && e > g1)) drops.push(g1);
  }
}

const out = {
  duration: 264.92, bpm: +bpm.toFixed(3), grid: { a: +a.toFixed(4), beat: +(2 * b).toFixed(5) },
  firstKick: snapped[0].t, kicks: snapped, breaks, drops, backing, lead,
  envFps: 20, env: { mix: env.mix, backing: env.backing, lead: env.lead },
};
fs.writeFileSync("../timing.js", "// generated by analysis/build-timing.mjs from the OUT OF STOCK stems\nwindow.OOS = " + JSON.stringify(out) + ";\n");
console.log("bpm", out.bpm, "grid a", out.grid.a, "kicks", snapped.length, "on-grid", N);
console.log("breaks", breaks.map(g => g.map(x => x.toFixed(1)).join("-")).join("  "));
console.log("drops", drops.map(x => x.toFixed(2)).join("  "));
