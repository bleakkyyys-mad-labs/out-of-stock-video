# The lead vocal as data (9/27: verse 3's sales-agent ring goes spiky, and the creator's "the spikes ride her voice"
# needed her voice's spectrum, not just its loudness; step 27's held "availaaaable" needed her pitch).
#   python analysis/lead-voice.py   ->  data/lead.js   (numpy + soundfile)
#
# Written: her spectrum per video frame through HIS analyzer chain (analysis\avs.py, the same chain and settings as
# the synth, so a band means the same thing on both), her loudness per frame, and her pitch every 10 ms (YIN) as a
# MIDI note, 0 where she isn't singing. The lead stem carries the chorus voice too (doubled on the backing stem).
import json, os
import numpy as np
from avs import load_mono, Framer, band_spectrum, loudness, yin_midi, b64

HERE = os.path.dirname(os.path.abspath(__file__))
STEM = os.path.join(HERE, "..", "..", "suno-songs", "out-of-stock", "2 Lead Vocal.wav")
OUT = os.path.join(HERE, "..", "data", "lead.js")

FPS, BANDS, F_LO, F_HI, N_FFT = 30, 48, 90.0, 16000.0, 2048
ATTACK, DECAY, GAMMA, RANGE_DB = 0.0, 0.55, 2.0, 48.0
PITCH_FPS = 100

x, sr = load_mono(STEM)
dur = len(x) / sr
nfr = int(np.floor(dur * FPS)) + 1
fr = Framer(x, sr, N_FFT)
shaped_u8, MAX_DB, FLOOR_DB = band_spectrum(fr, nfr, FPS, BANDS, F_LO, F_HI, ATTACK, DECAY, GAMMA, RANGE_DB)
rms_db, env_u8 = loudness(fr, nfr, FPS)
midi = yin_midi(x, sr, PITCH_FPS)
pitch_u16 = np.round(midi * 100).astype(np.uint16)       # hundredths of a semitone; 0 = not singing

data = {
    "fps": FPS, "bands": BANDS, "fLo": F_LO, "fHi": F_HI, "frames": nfr,
    "shaped": b64(shaped_u8), "env": b64(env_u8),
    "pitchFps": PITCH_FPS, "pitchFrames": len(pitch_u16), "pitch": b64(pitch_u16.astype("<u2")),
    "params": {"nfft": N_FFT, "attack": ATTACK, "decay": DECAY, "gamma": GAMMA, "maxDb": round(MAX_DB, 2), "floorDb": round(FLOOR_DB, 2)},
}
with open(OUT, "w", encoding="utf8") as f:
    f.write("// generated by analysis/lead-voice.py from the lead vocal stem, 2 Lead Vocal.wav (the creator's audio-visualizer plugin's analyzer chain, log bands; YIN pitch)\n")
    f.write("window.OOS_LEAD = " + json.dumps(data, separators=(",", ":")) + ";\n")
voiced = midi > 0
print(f"{nfr} frames x {BANDS} bands at {FPS} fps  ·  maxDb {MAX_DB:.1f}  floor {FLOOR_DB:.1f}  ·  pitch {len(midi)} frames at {PITCH_FPS} fps, {voiced.mean() * 100:.0f}% voiced")
for a, b in [(207.9, 210.9)]:
    seg = [(i / PITCH_FPS, midi[i]) for i in range(int(a * PITCH_FPS), int(b * PITCH_FPS)) if i % 5 == 0]
    print(" ".join(f"{t:.2f}:{m:.1f}" for t, m in seg))
print(f"wrote {os.path.relpath(OUT)}  {os.path.getsize(OUT) / 1024:.0f} KB")
