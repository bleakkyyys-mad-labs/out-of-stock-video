# The synth stem as data (the creator's stem, 9/27 00:38: "OOM (Synth).wav", the synths that carry the intro).
#   python analysis/synth-spectrum.py   ->  data/synth.js   (numpy + soundfile)
#
# The spectrum is the creator's analyzer chain (analysis\avs.py, where the chain now lives so the lead vocal can go through it
# too). Also written: the synth's loudness per frame, its note onsets (the 16th-note gates), and the spans where it
# plays.
import json, os
import numpy as np
from avs import load_mono, Framer, band_spectrum, loudness, b64

HERE = os.path.dirname(os.path.abspath(__file__))
STEM = os.path.join(HERE, "..", "..", "suno-songs", "out-of-stock", "OOM (Synth).wav")
OUT = os.path.join(HERE, "..", "data", "synth.js")

FPS = 30                        # the video's frame rate (song.js FPS): frame n is t = n / 30
BANDS, F_LO, F_HI = 48, 90.0, 16000.0
N_FFT = 2048                    # 42.7 ms at 48 kHz (the reference's window)
ATTACK, DECAY = 0.0, 0.55       # the reference's semantics: new = prev + (cur - prev) * (1 - k); 0 = instant
GAMMA = 2.0                     # the reference's default
RANGE_DB = 48.0                 # noise floor = max - 48 dB; max = the 99.7th percentile of the song's band levels
ON_DB, OFF_DB = -40.0, -46.0    # the synth is playing: loudness above -40 dBFS, until it falls under -46

x, sr = load_mono(STEM)
dur = len(x) / sr
nfr = int(np.floor(dur * FPS)) + 1
fr = Framer(x, sr, N_FFT)

shaped_u8, MAX_DB, FLOOR_DB = band_spectrum(fr, nfr, FPS, BANDS, F_LO, F_HI, ATTACK, DECAY, GAMMA, RANGE_DB)
rms_db, env_u8 = loudness(fr, nfr, FPS)

# --- spans where the synth plays (hysteresis on the loudness)
spans, on, t0 = [], False, 0.0
for i, v in enumerate(rms_db):
    t = i / FPS
    if not on and v > ON_DB: on, t0 = True, t
    elif on and v < OFF_DB:
        on = False
        if t - t0 >= 0.5: spans.append([t0, t])
if on: spans.append([t0, dur])
merged = []
for a, b in spans:
    if merged and a - merged[-1][1] < 0.3: merged[-1][1] = b
    else: merged.append([a, b])

# --- note onsets: spectral flux on a fine hop, peaks over a local median, only where the synth is playing
HOP_O = 256
tt = np.arange(0, dur, HOP_O / sr)
flux = np.zeros(len(tt), np.float32)
prevs = None
win_o = np.hanning(N_FFT).astype(np.float32)
for s in range(0, len(tt), 4000):
    spec = np.abs(np.fft.rfft(fr.at(tt[s:s + 4000], N_FFT, win_o), axis=1)).astype(np.float32)
    spec = np.log1p(spec * 10)
    if prevs is not None: spec_full = np.vstack([prevs[None], spec])
    else: spec_full = np.vstack([spec[:1], spec])
    d = np.maximum(np.diff(spec_full, axis=0), 0).sum(axis=1)
    flux[s:s + len(d)] = d
    prevs = spec[-1]
# (a median over a whole second: the synth's notes are 8ths with rests, and a short window's median sat on the notes
# themselves in the dense bars, which hid real notes; over a second it sits on the texture between them)
MW = int(1.0 * sr / HOP_O)
med = np.array([np.median(flux[max(0, i - MW):i + MW]) for i in range(len(flux))])
rel = flux / (med + 1e-6)
loud_at = lambda t: rms_db[min(nfr - 1, int(round(t * FPS)))]
onsets, last = [], -1.0
peak_all = np.percentile(flux, 99.5)
for i in range(1, len(flux) - 1):
    if flux[i] < flux[i - 1] or flux[i] < flux[i + 1] or rel[i] < 1.6: continue
    t = float(tt[i])
    if loud_at(t) < -48: continue
    strength = float(min(1.0, flux[i] / peak_all))
    if onsets and t - onsets[-1][0] < 0.11:                   # one per note (a note re-strikes ~70 ms in): keep the stronger
        if strength > onsets[-1][1]: onsets[-1] = [t, strength]
        continue
    onsets.append([t, strength])

data = {
    "fps": FPS, "bands": BANDS, "fLo": F_LO, "fHi": F_HI, "frames": nfr,
    "shaped": b64(shaped_u8), "env": b64(env_u8),
    "onsets": [[round(t, 4), round(s, 3)] for t, s in onsets],
    "spans": [[round(a, 3), round(b, 3)] for a, b in merged],
    "params": {"nfft": N_FFT, "attack": ATTACK, "decay": DECAY, "gamma": GAMMA, "maxDb": round(MAX_DB, 2), "floorDb": round(FLOOR_DB, 2),
               "on": ON_DB, "off": OFF_DB},
}
with open(OUT, "w", encoding="utf8") as f:
    f.write("// generated by analysis/synth-spectrum.py from the synth stem, OOM (Synth).wav (the reference visualizer's analyzer chain, log bands)\n")
    f.write("window.OOS_SYNTH = " + json.dumps(data, separators=(",", ":")) + ";\n")
intro = [o for o in onsets if o[0] < 21]
print(f"{nfr} frames x {BANDS} bands at {FPS} fps  ·  maxDb {MAX_DB:.1f}  floor {FLOOR_DB:.1f}  ·  {len(onsets)} onsets ({len(intro)} before 21 s)")
print("spans:", [[round(a, 2), round(b, 2)] for a, b in merged][:12], "..." if len(merged) > 12 else "")
print("intro onsets:", [round(o[0], 2) for o in intro])
print(f"wrote {os.path.relpath(OUT)}  {os.path.getsize(OUT) / 1024:.0f} KB")
