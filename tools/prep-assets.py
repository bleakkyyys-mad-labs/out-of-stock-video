# Engine-side assets from the cutouts and the alignment (pixl env):
#   assets/tex/<key>.png  - cutouts at 2048 px wide (plenty for 1080p; keeps GPU memory sane)
#   assets/tex/<key>.jpg  - full-frame photos (the backgrounds), 2048 px wide, no alpha
#   data/cutouts.js       - window.OOS_CUTOUTS: key, texture, aspect, outline polygon (0..1 uv, y down)
#   data/lyrics.js        - window.OOS_LYRICS: the aligned sung words + sheet lines
#   every texture goes through tools/debrand.py first (the creator's ruling, 9/26: no real branding in the video); a texture
#   with no regions in assets/debrand.json is written as it is, and named in a warning
import json, os, re, sys
import numpy as np
import cv2

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from debrand import apply as debrand, load as debrand_regions

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A, TEX = os.path.join(ROOT, "assets"), os.path.join(ROOT, "assets", "tex")
os.makedirs(TEX, exist_ok=True)
os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)

# (folder, {file prefix: key}, full-frame?)
SETS = [
    ("gpu-cutouts", {"018": "pile", "020": "rtx3090", "022": "rog-pair", "025": "rtx3070", "040": "radeon7790",
                     "051": "gtx1080ti", "052": "gtx1080ti-fan", "053": "gtx1080ti-hub", "057": "gtx1080ti-io", "058": "gtx1080ti-back"}, False),
    ("ram-cutouts", {"105": "ddr4-16g", "301": "fury-ddr4", "302": "fury-ddr4-back", "303": "samsung-ddr4", "304": "fury-white",
                     "306": "z5-stack", "307": "ddr4-vs-ddr5", "308": "z5-x-dark", "309": "z5-x-white", "310": "fury-ddr5",
                     "311": "z5-black", "312": "z5-white", "313": "dominator", "315": "micron-rdimm", "316": "micron-rdimm-label",
                     "318a": "hynix-mrdimm"}, False),
    (os.path.join("photos", "ram"), {"305": "bg-rgb-pc", "314": "bg-ddr5-table", "317": "bg-hynix-boards",
                                     "318-": "bg-hynix-mrdimm", "319": "bg-empty-slots"}, True),
    ("parts-cutouts", {"401a": "cpu", "402": "ssd", "403": "psu"}, False),
    (os.path.join("photos", "dc"), {"501": "bg-dc-halls", "502": "bg-dc-hall"}, True),
    (os.path.join("photos", "eye"), {"601": "bg-eye"}, True),
]
out, REG, unbranded = [], debrand_regions(), []
for folder, keys, full in SETS:
    for f in sorted(os.listdir(os.path.join(A, folder))):
        key = next((k for p, k in keys.items() if f.startswith(p) and (len(p) > 3 or f[3] == "-")), None)
        if key is None:
            continue
        im = cv2.imread(os.path.join(A, folder, f), cv2.IMREAD_COLOR if full else cv2.IMREAD_UNCHANGED)
        h, w = im.shape[:2]
        s = min(1.0, 2048 / w)
        im = cv2.resize(im, (round(w * s), round(h * s)), interpolation=cv2.INTER_AREA)
        h, w = im.shape[:2]
        if key in REG:
            im = debrand(key, im, REG)
        else:
            unbranded.append(key)
        if full:
            tex = f"assets/tex/{key}.jpg"
            cv2.imwrite(os.path.join(TEX, key + ".jpg"), im, [cv2.IMWRITE_JPEG_QUALITY, 92])
            c = np.array([[0, 0], [w, 0], [w, h], [0, h]])
        else:
            tex = f"assets/tex/{key}.png"
            cv2.imwrite(os.path.join(TEX, key + ".png"), im, [cv2.IMWRITE_PNG_COMPRESSION, 6])
            a = (im[:, :, 3] > 127).astype(np.uint8)
            cs, _ = cv2.findContours(a, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
            c = max(cs, key=cv2.contourArea)
            c = cv2.approxPolyDP(c, 0.0025 * cv2.arcLength(c, True), True)[:, 0, :]
        # lum: the photo's median tone as the screentone shader sees it (sRGB luma), so a shot can print every
        # stick's board at the same tone whatever its colour
        lin = (im[:, :, :3].astype(np.float32) / 255) ** 2.2
        L = (lin[:, :, 2] * 0.2126 + lin[:, :, 1] * 0.7152 + lin[:, :, 0] * 0.0722) ** 0.4545
        solid = im[:, :, 3] > 127 if im.shape[2] == 4 else np.ones(L.shape, bool)
        out.append({"key": key, "src": f, "tex": tex, "w": w, "h": h, "aspect": round(w / h, 5), "lum": round(float(np.median(L[solid])), 3),
                    "outline": [[round(x / w, 4), round(y / h, 4)] for x, y in c]})
        print(f"{key:20} {w}x{h}  outline {len(c)} pts")
if unbranded:
    print("NOT DEBRANDED (no regions in assets/debrand.json; check before a shot uses one):", ", ".join(unbranded))
open(os.path.join(ROOT, "data", "cutouts.js"), "w", encoding="utf-8").write(
    "// generated by tools/prep-assets.py\nwindow.OOS_CUTOUTS = " + json.dumps(out) + ";\n")

L = json.load(open(os.path.join(ROOT, "analysis", "lyrics-aligned.json"), encoding="utf-8"))
open(os.path.join(ROOT, "data", "lyrics.js"), "w", encoding="utf-8").write(
    "// generated by tools/prep-assets.py from analysis/lyrics-aligned.json\nwindow.OOS_LYRICS = "
    + json.dumps({"lines": L["lines"], "sung": L["sung"]}) + ";\n")
print("lyrics:", len(L["sung"]), "sung words,", len(L["lines"]), "lines")
